import { browser } from "wxt/browser";
import { parseTimestamp } from "./timestamps";

/**
 * The video's own transcript, read from YouTube's transcript panel.
 *
 * YouTube no longer serves caption files or its transcript API to plain
 * requests (they need a per-session token only the page can make), so the
 * reliable source is the page itself: open YouTube's transcript panel,
 * invisibly, read its rows, and close it again. The panel stays inside the
 * viewport (just transparent and behind the page) because YouTube only loads
 * the rows once their placeholder is on screen.
 */

export interface TranscriptLine {
  /** Seconds into the video. */
  time: number;
  text: string;
  /** A chapter title rather than spoken text. */
  heading?: boolean;
}

export interface Transcript {
  lines: TranscriptLine[];
  /** Captions YouTube generated by speech recognition. */
  auto: boolean;
}

const PREFIX = "transcript:";
const PANEL = 'ytd-engagement-panel-section-list-renderer[target-id*="transcript"]';
const SEGMENT = "transcript-segment-view-model, ytd-transcript-segment-renderer";
const HEADING = "ytd-transcript-section-header-renderer, timeline-chapter-view-model";
const HIDE_ATTR = "data-notavid-transcript";
const EXPANDED = "ENGAGEMENT_PANEL_VISIBILITY_EXPANDED";

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function hideStyle() {
  if (document.getElementById("notavid-transcript-style")) return;
  const style = document.createElement("style");
  style.id = "notavid-transcript-style";
  style.textContent = `html[${HIDE_ATTR}] ${PANEL} {
    position: fixed !important; top: 64px !important; left: 0 !important;
    width: 400px !important; height: 70vh !important;
    opacity: 0 !important; z-index: -1 !important; pointer-events: none !important;
  }`;
  document.head.append(style);
}

const openPanel = () =>
  [...document.querySelectorAll<HTMLElement>(PANEL)].find(
    (p) => p.getAttribute("visibility") === EXPANDED && p.querySelector(SEGMENT),
  );

function readPanel(panel: HTMLElement): Transcript {
  const lines: TranscriptLine[] = [];
  let pendingHeading: string | null = null;
  for (const el of panel.querySelectorAll<HTMLElement>(`${SEGMENT}, ${HEADING}`)) {
    if (el.matches(HEADING)) {
      pendingHeading = el.querySelector("h2, .title, [class*='Title']")?.textContent?.trim() || el.innerText.split("\n")[0]?.trim() || null;
      continue;
    }
    const stamp = el.querySelector(".ytwTranscriptSegmentViewModelTimestamp, .segment-timestamp")?.textContent ?? "";
    const time = parseTimestamp(stamp);
    const text = (el.querySelector(".ytAttributedStringHost, .segment-text")?.textContent ?? "").replace(/\s+/g, " ").trim();
    if (time == null || !text) continue;
    if (pendingHeading) {
      lines.push({ time, text: pendingHeading, heading: true });
      pendingHeading = null;
    }
    lines.push({ time, text });
  }
  // The language picker reads e.g. "English (auto-generated)".
  const rest = panel.cloneNode(true) as HTMLElement;
  rest.querySelectorAll(SEGMENT).forEach((e) => e.remove());
  const auto = /auto-generated|automatically|تلقائي|automatique|automático|automatisch/i.test(rest.textContent ?? "");
  return { lines, auto };
}

function closePanel(panel: HTMLElement) {
  const close =
    panel.querySelector<HTMLElement>("#visibility-button button") ??
    panel.querySelector<HTMLElement>('button[aria-label*="Close" i], button[aria-label*="إغلاق"]');
  close?.click();
}

let inFlight: { videoId: string; promise: Promise<Transcript | null> } | null = null;

/**
 * Read the transcript of the video on the page. Resolves null when the video
 * has none; throws when YouTube didn't deliver it in time.
 */
export function readTranscript(videoId: string): Promise<Transcript | null> {
  if (inFlight?.videoId === videoId) return inFlight.promise;
  const promise = scrape(videoId).finally(() => {
    if (inFlight?.promise === promise) inFlight = null;
  });
  inFlight = { videoId, promise };
  return promise;
}

async function scrape(videoId: string): Promise<Transcript | null> {
  // Wait for the watch page to actually show this video (SPA navigation).
  for (let i = 0; i < 40 && document.querySelector("ytd-watch-flexy")?.getAttribute("video-id") !== videoId; i++) {
    await sleep(250);
  }
  // The user already has YouTube's transcript open: just read it.
  const open = openPanel();
  if (open) return readPanel(open);

  let button: HTMLElement | null = null;
  for (let i = 0; i < 12 && !button; i++) {
    button = document.querySelector<HTMLElement>("ytd-video-description-transcript-section-renderer button");
    if (!button) await sleep(250);
  }
  if (!button) return null;

  hideStyle();
  document.documentElement.setAttribute(HIDE_ATTR, "");
  let panel: HTMLElement | undefined;
  try {
    button.click();
    // Rows arrive in one go but render over a few frames: wait until the
    // count stops growing.
    let count = 0;
    let steady = 0;
    for (let i = 0; i < 80 && steady < 3; i++) {
      await sleep(250);
      panel = openPanel();
      const n = panel?.querySelectorAll(SEGMENT).length ?? 0;
      steady = n > 0 && n === count ? steady + 1 : 0;
      count = n;
    }
    if (!panel) throw new Error("transcript didn't load");
    return readPanel(panel);
  } finally {
    const shown = panel ?? [...document.querySelectorAll<HTMLElement>(PANEL)].find((p) => p.getAttribute("visibility") === EXPANDED);
    if (shown) closePanel(shown);
    // Let YouTube finish closing before the panel can show again.
    setTimeout(() => document.documentElement.removeAttribute(HIDE_ATTR), 400);
  }
}

export async function loadSavedTranscript(videoId: string): Promise<Transcript | null> {
  const items = await browser.storage.local.get(PREFIX + videoId);
  return (items[PREFIX + videoId] as Transcript | undefined) ?? null;
}

export async function saveTranscript(videoId: string, transcript: Transcript) {
  await browser.storage.local.set({ [PREFIX + videoId]: transcript });
}
